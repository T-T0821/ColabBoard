//! 構成図の部品(`board_core::diagram::catalog` の種類)と、公式アイコンパック内のファイル名の対応。
//!
//! ファイル名は大文字小文字・記号を無視して比べる(`normalize`)。
//! - AWS: サイズ(`_64` など)と `_Light`/`_Dark` を除いたファイル名と完全一致
//! - Azure: 先頭の `10021-icon-service-` を除いたファイル名と完全一致
//! - Google Cloud: パス全体に含まれるか(パックの構成が版ごとに違うため)
//!
//! パックの版が変わって名前がずれたら、ここに候補を足す。

